#分别打印切词结果和相同的分词


text1 = "哪三种模型评估方法？"
text2 = "过拟合是由于模型的学习能力相对于数据来说过于强大，反过来说，欠拟合是因为模型的学习能力相\n对于数据来说过于低下。暂且抛开“没有免费的午餐”定理不谈，例如对于“西瓜书”第1 章图1.4 中的\n训练样本（黑点）来说，用类似于抛物线的曲线A 去拟合则较为合理，而比较崎岖的曲线B 相对于训练\n样本来说学习能力过于强大，但若仅用一条直线去训练则相对于训练样本来说直线的学习能力过于低下。\n2.2\n评估方法\n本节介绍了3 种模型评估方法：留出法、交叉验证法、自助法。留出法由于操作简单，因此最常用；\n交叉验证法常用于对比同一算法的不同参数配置之间的效果，以及对比不同算法之间的效果；自助法常用\n于集成学习（详见“西瓜书”第8 章的8.2 节和8.3 节）产生基分类器。留出法和自助法简单易懂，在此\n不再赘述，下面举例说明交叉验证法的常用方式。"

words1 = list(jieba.cut(text1))
words2 = list(jieba.cut(text2))

print("切词结果:")
print(f"文本1: {words1}")
print(f"文本2: {words2}")

print("\n相同分词:")
common_words = set(words1) & set(words2)
print(common_words)